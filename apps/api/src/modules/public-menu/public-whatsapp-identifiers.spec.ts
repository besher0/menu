import { describe, expect, it } from "vitest";
import { slugify } from "../../common/slugify";
import { parseWhatsappCheckoutRequest } from "./public-whatsapp-checkout.contract";
describe("ordinary product identifiers in mixed V2 checkout", () => {
 const body=(slug:string)=>({locale:"ar",fulfillmentType:"pickup",items:[{mode:"LEGACY",lineId:`legacy:${slug}`,productSlug:slug,productId:"ordinary-product-id",quantity:1,expectedUnitPrice:"200"},{mode:"NETWORK",lineId:"network-1",productId:"pizza",quantity:1,selection:{schemaVersion:2,productId:"pizza",configurationRevision:1,groups:[]}}]});
 it("accepts the Arabic slug generated by the actual unified editor and the cart's existing line ID",()=>{
  const slug=slugify("منتج عادي");expect(slug).toBe("منتج-عادي");expect(parseWhatsappCheckoutRequest(body(slug)).items[0].productSlug).toBe(slug);
 });
 it("rejects missing ordinary product identity",()=>{const request=body("water");delete (request.items[0] as {productId?:string}).productId;expect(()=>parseWhatsappCheckoutRequest(request)).toThrow()});
 it.each(["bad/slug","../escape","bad\nslug","bad\u202eslug","bad slug","x".repeat(129)])("rejects non-identifier characters/overlength %s",slug=>{
  expect(()=>parseWhatsappCheckoutRequest(body(slug))).toThrow();
 });
});
